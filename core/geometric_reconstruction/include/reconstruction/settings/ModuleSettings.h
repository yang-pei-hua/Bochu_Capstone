// One externalised knob. Getter/setter functions keep the option struct layout
// untouched while allowing the settings UI and CLI to work generically.
template <class Options>
struct Setting {
    enum class Type { Integer, Real, Boolean };
    const char* key;
    const char* group;
    const char* label;
    Type type;
    double minimum;
    double maximum;
    double (*value)(const Options&);
    void (*assign)(Options&, double);
};

struct Field {
    std::string key;
    std::string group;
    std::string label;
    int type = 1;  // 0 integer, 1 real, 2 boolean
    double minimum = 0;
    double maximum = 0;
};

// Type-erased document used by the settings dialog and the module CLIs.
class Document {
public:
    virtual ~Document() = default;
    virtual std::string id() const = 0;
    virtual std::string title() const = 0;
    virtual std::string filename() const = 0;
    virtual const std::vector<Field>& fields() const = 0;
    virtual double value(std::size_t index) const = 0;
    virtual void setValue(std::size_t index, double value) = 0;
    virtual std::string serialize() const = 0;
    virtual void validate() const = 0;
    // Applies every key present in the file onto the current defaults.
    virtual void load(const std::filesystem::path& path) = 0;
    virtual void applyOverrides() = 0;
};

using DocumentPtr = std::unique_ptr<Document>;

